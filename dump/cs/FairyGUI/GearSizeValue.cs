namespace FairyGUI;

internal class GearSizeValue
{
	public float width;

	public float height;

	public float scaleX;

	public float scaleY;

	public GearSizeValue(float width, float height, float scaleX, float scaleY)
	{
		this.width = width;
		this.height = height;
		this.scaleX = scaleX;
		this.scaleY = scaleY;
	}
}
